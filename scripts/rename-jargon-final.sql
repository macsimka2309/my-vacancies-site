BEGIN;
-- Финальная формулировка 04.09, после двух правок по замечаниям владельца:
-- «большой багажник» звучал как характеристика курьера, а не машины;
-- «Курьер (универсал)» отдельно оказался двусмыслен — неясно, о машине
-- речь или о специальности курьера. «Курьер на а/м (универсал)» снимает
-- обе двусмысленности: сначала транспорт, тип кузова — уточнением в скобках.
UPDATE vacancies SET title = 'Курьер на а/м (универсал)' WHERE title = 'Курьер (большой багажник)';
UPDATE vacancies SET work_format = 'Авто (универсал)' WHERE work_format = 'Авто (большой багажник)';
COMMIT;
