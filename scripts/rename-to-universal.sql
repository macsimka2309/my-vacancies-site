-- Правка по просьбе владельца 04.09: «большой багажник» звучит как
-- личная характеристика курьера, а не свойство машины. «Универсал» —
-- нейтральный автомобильный термин, уже используется в FAQ п.13
-- (lib/intents.ts: «универсал вроде Лады Ларгус»).
