// Отображаемое имя проекта: мы — официальный партнёр бренда, поэтому
// показываем «официальный партнёр Магнит». В БД хранится «сырое» имя
// («Магнит») — от него зависят слаги, фильтры и дедупликация.
// Модуль намеренно без серверных зависимостей, чтобы использоваться и
// в клиентских компонентах (ApplyButton).
export function formatProject(project: string) {
  return `официальный партнёр ${project}`;
}
