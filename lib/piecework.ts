/**
 * Разбор сдельной оплаты (п. 9).
 *
 * У 88 вакансий из 169 часовой ставки нет по договору: в таблице партнёра
 * стоит `час 0р` у Ленты и `Гарант доход в час — 0` у Магнита. Платят за
 * события — за заказ, за километр, за перевес. Это и есть ответ на вопрос
 * «сколько платят», а «до 7 100 ₽ за смену» — только его потолок.
 *
 * Таблица описывает одно и то же двумя способами, поэтому разборщика два:
 *
 *   Лента, одна строка:  «час 0р/заказ 148р перевес свыше 20 кг-60р,
 *                         перепробег-11,2 р, Мин смена - 12 ч»
 *   Магнит, список пар:  «Км в пути от М до ТТ - 19
 *                         Повышенное взятие - 68
 *                         Повышенное вручение - 42»
 *
 * Складывать составляющие между собой мы не беремся: «взятие» и «вручение»
 * у Магнита — два события одного заказа, но что курьер получает и то и другое
 * за каждый заказ, таблица не утверждает. Показываем то, что в ней написано.
 */

/** Ключ составляющей: по нему решают, что вынести на карточку. */
export type PieceworkKey =
  | "order"
  | "pickup"
  | "handover"
  | "kmToStore"
  | "kmToClient"
  | "overrun"
  | "heavy"
  | "oversize"
  | "guaranteeHour"
  | "minShift";

export type PieceworkPart = {
  key: PieceworkKey;
  /** Подпись для человека — без жаргона таблицы («ТТ», «КГТ», «перепробег»). */
  label: string;
  value: number;
};

/**
 * Словарь таблицы. Ключ — как написано у партнёра, значение — что это
 * значит и как это назвать соискателю.
 *
 * «ТТ» — торговая точка, «М» — магазин, «К» — клиент, «КГТ» —
 * крупногабаритный товар. Соискателю эти сокращения не говорят ничего,
 * поэтому в подписи их нет ни одного.
 */
const DICTIONARY: { match: RegExp; key: PieceworkKey; label: string }[] = [
  // Порядок важен: «за забор заказа» должно разбираться раньше «заказ»,
  // иначе первое попадёт во второе и станет ценой заказа.
  {
    match: /^(?:оплата\s+)?за\s*забор(?:\s+заказа)?$|^забор\s+заказа$|^подбор\s+заказа$|^повышенн(?:ое|ый)\s+(?:взятие|подбор)$/i,
    key: "pickup",
    label: "за сбор заказа",
  },
  {
    match: /^повышенное\s+вручение$|^вручение\s+заказа$/i,
    key: "handover",
    label: "за вручение заказа",
  },
  {
    match: /^(?:кгт\s+заказ[ыа]?|заказ\s+кгт)$/i,
    key: "oversize",
    label: "за крупногабаритный заказ",
  },
  {
    match: /^(?:оплата\s+)?(?:за\s+)?заказ$/i,
    key: "order",
    label: "за заказ",
  },
  {
    match: /^(?:км\s+в\s+пути\s+)?от\s+м\s+до\s+тт$|^пробег,?\s*км\s+от\s+м\s+до\s+тт$/i,
    key: "kmToStore",
    label: "за километр до магазина",
  },
  {
    match: /^(?:км\s+в\s+пути\s+)?от\s+тт\s+до\s+к$|^пробег,?\s*км\s+от\s+тт\s+до\s+к$/i,
    key: "kmToClient",
    label: "за километр до клиента",
  },
  {
    match: /^пробег,?\s*км$|^перепробег$/i,
    key: "overrun",
    label: "за километр сверх маршрута",
  },
  {
    match: /^бонус:?\s*тяжелый\s+заказ$/i,
    key: "heavy",
    label: "за тяжёлый заказ",
  },
  {
    match: /^гарант(?:ированный)?\s+доход\s+в\s+час$/i,
    key: "guaranteeHour",
    label: "гарантия за час",
  },
  {
    match: /^минималка\s+(?:за|при\s+выработке)\s+12\s+часов$/i,
    key: "minShift",
    label: "минимум за 12-часовую смену",
  },
];

/** «перевес свыше 20 кг» — порог в подписи, поэтому отдельно от словаря. */
const OVERWEIGHT = /^перевес\s+свыше\s+(\d+)\s*кг$/i;

/**
 * Числа, которые в таблице есть, но составляющими оплаты не являются.
 *
 * «Доход в час» у Магнита — это «Доход в день», делённый на 12-часовую смену,
 * а не тариф. «Доход в день» и «в месяц» — потолки, они уже стоят на карточке
 * как «до N ₽ за смену». «Пороги минималки» и «Повышающий коэффициент» —
 * служебные поля расчёта.
 */
const IGNORED =
  /^доход\s+в\s+(?:день|час|мес(?:яц)?)$|^пороги\s+минималки$|^повышающий\s+коэффициент$|мин\.?\s*смена|^\d+\s*з$|^(?:мск|мо|спб|ло|тарифы)(?![а-яё])/i;

export function parsePiecework(text: string | null | undefined): PieceworkPart[] {
  if (!text?.trim()) {
    return [];
  }

  const found = new Map<string, PieceworkPart>();

  for (const [rawLabel, rawValue] of readPairs(text)) {
    // Подпись приходит вместе с хвостом предыдущей составляющей —
    // «, перепробег-» или «/заказ». Отрезаем разделители с обоих концов.
    const label = rawLabel
      .replace(/\s+/g, " ")
      .replace(/^[\s,;./|·-]+/, "")
      .replace(/[\s:-]+$/, "")
      .trim();

    if (!label || IGNORED.test(label)) {
      continue;
    }

    const value = Number(rawValue.replace(",", "."));

    // Ноль — это «такой составляющей нет»: у Магнита `Гарант доход в час — 0`
    // означает, что гарантии нет, а не что она нулевая. Коэффициент 1 —
    // отсутствие коэффициента.
    if (!Number.isFinite(value) || value <= 0) {
      continue;
    }

    const overweight = label.match(OVERWEIGHT);

    if (overweight) {
      // Порогов бывает три (20, 40, 75 кг) — каждый со своей ценой.
      addPart(found, {
        key: "heavy",
        label: `за вес свыше ${overweight[1]} кг`,
        value,
      });
      continue;
    }

    const entry = DICTIONARY.find((item) => item.match.test(label));

    if (entry) {
      addPart(found, { key: entry.key, label: entry.label, value });
    }
  }

  return [...found.values()];
}

/**
 * Головное число для карточки — цена заказа.
 *
 * Только там, где таблица называет её прямо. У Магнита цены заказа нет:
 * есть «взятие» и «вручение» по отдельности, и складывать их за партнёра
 * мы не будем — это была бы наша цифра, а не его.
 */
export function getPayPerOrder(parts: PieceworkPart[]) {
  return parts.find((part) => part.key === "order")?.value ?? null;
}

/** «за заказ 148 ₽» — подпись для карточки списка. */
export function formatPayPerOrder(value: number | null | undefined) {
  if (!value) {
    return null;
  }

  return `за заказ ${formatPartValue(value)}`;
}

/**
 * «148 ₽». Копейки убираем округлением вниз — по той же причине, что и
 * у часовой ставки (lib/salary.ts): названная сумма это обещание, и 148
 * при тарифе 148,8 человек получит, а 149 — нет.
 */
export function formatPartValue(value: number) {
  return `${new Intl.NumberFormat("ru-RU").format(Math.floor(value))} ₽`;
}

/**
 * Пары «подпись — число» из обоих форматов таблицы.
 *
 * Список Магнита распознаётся по переводам строки, строка Ленты — по
 * разделителям `/` и `,`. Формат определяется тем, что нашлось, а не
 * названием листа: в таблице встречаются оба у одного проекта.
 */
function readPairs(text: string): [string, string][] {
  const pairs: [string, string][] = [];

  for (const line of text.split(/\n+/)) {
    // Магнит: «Повышенное вручение - 42» — вся строка одна пара.
    //
    // Подпись берём жадно, до **последнего** разделителя: в «Бонус: тяжелый
    // заказ - 25» двоеточие стоит внутри самой подписи, и ленивый разбор
    // обрывал её на «Бонус», после чего строка не находилась вовсе.
    const whole = line.match(/^\s*(.{3,45})\s*[-–:]\s*(\d+(?:[.,]\d+)?)\s*$/);

    if (whole) {
      pairs.push([whole[1], whole[2]]);
      continue;
    }

    // Лента: «час 0р/заказ 148р перевес свыше 20 кг-60р, перепробег-11,2 р».
    //
    // Разделителя между составляющими нет — «заказ 148р» и «перевес свыше
    // 20 кг-60р» разделены пробелом. Поэтому идём от сумм: всё, что стоит
    // между предыдущей суммой и текущей, и есть подпись. Иначе метки с
    // числом внутри («свыше 20 кг») распадаются на части.
    let cursor = 0;

    // `\b` здесь не годится: JS считает границей слова только ASCII, а после
    // кириллической «р» её не возникает — регулярное выражение с `р\b`
    // не находило ни одной суммы. Отсекаем «руб» просмотром вперёд.
    // Рубль после суммы стоит не всегда: «заказ КГТ- 702,31,» обрывается
    // запятой. Без второго варианта эта сумма пропускалась, а её подпись
    // прилипала к следующей составляющей.
    for (const match of line.matchAll(
      /(\d+(?:[.,]\d+)?)\s*(?:р(?![а-яё])|(?=\s*,))/gi,
    )) {
      pairs.push([line.slice(cursor, match.index), match[1]]);
      cursor = match.index + match[0].length;
    }
  }

  return pairs;
}

/** Первое упоминание выигрывает: в строке Ленты тарифы идут от общего к частному. */
function addPart(found: Map<string, PieceworkPart>, part: PieceworkPart) {
  const id = `${part.key}:${part.label}`;

  if (!found.has(id)) {
    found.set(id, part);
  }
}
