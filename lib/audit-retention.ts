import { db } from "./db";

/**
 * Срок хранения журнала изменений.
 *
 * Журнал пишется на каждую правку статуса и примечания, а также на ручное
 * создание отклика. Читает его только страница `/admin/logs`, и та берёт
 * всё разом, без ограничения — то есть таблица растёт без потолка, а
 * страница вместе с ней. Сегодня это 20 записей и 80 КБ, так что чистка
 * ничего не удалит; смысл в том, чтобы не пришлось разбираться с этим
 * через год.
 *
 * Срок задан владельцем 25.08: хранить месяц. Помнить о том, что это
 * короткий срок для журнала действий: после чистки на вопрос «кто перевёл
 * кандидата в отказ полгода назад» ответа уже не будет.
 */
export const AUDIT_RETENTION_DAYS = 30;

/**
 * Чистка запускается не по расписанию, а изредка при самой записи в журнал.
 * Отдельный планировщик ради одной таблицы, в которую пишут пару раз в день,
 * — лишняя движущаяся часть: его надо ставить, следить, что он жив, и
 * чинить, когда он тихо умрёт. Тот же приём уже работает в rate-limit.
 */
const CLEANUP_CHANCE = 0.05;

export function getAuditCutoff(now = new Date()) {
  return new Date(now.getTime() - AUDIT_RETENTION_DAYS * 24 * 60 * 60 * 1000);
}

/** Удаляет записи журнала старше срока. Возвращает число удалённых. */
export async function purgeOldAuditLogs() {
  const { count } = await db.applicationAuditLog.deleteMany({
    where: {
      createdAt: {
        lt: getAuditCutoff(),
      },
    },
  });

  return count;
}

/**
 * Вызывается после записи в журнал. Никогда не бросает исключение: правка
 * отклика не должна падать из-за неудавшейся уборки — она уже сохранена.
 */
export async function maybePurgeOldAuditLogs() {
  if (Math.random() >= CLEANUP_CHANCE) {
    return;
  }

  try {
    const count = await purgeOldAuditLogs();

    if (count > 0) {
      console.info(`Журнал изменений: удалено записей старше ${AUDIT_RETENTION_DAYS} дней — ${count}.`);
    }
  } catch (error) {
    console.error("Не удалось почистить журнал изменений:", error);
  }
}
